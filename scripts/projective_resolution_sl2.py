def idx(a, b, c):
    return a * ELL * ELL + b * ELL + c

def from_idx(i):
    return i // (ELL*ELL), (i // ELL) % ELL, i % ELL

def weight(i):
    a, b, c = from_idx(i)
    return (2*b - 2*c) % ELL

