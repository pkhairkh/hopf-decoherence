def build_left_action_matrices(mult):
    """Build L_g[i] = matrix of left-multiplication by basis[i], shape (DIM, DIM).
    L_g[i] @ v = (basis[i] * v) as a vector."""
    L = np.zeros((DIM, DIM, DIM), dtype=complex)
    for i in range(DIM):
        for j in range(DIM):
            for k in range(DIM):
                L[i, j, k] = mult[k, i, j]  # mult[k,i,j] = coeff of basis[k] in (basis[i]*basis[j])
        # Wait: (basis[i] * basis[j]) = Σ_k mult[k,i,j] * basis[k]
        # So L_g[i] @ e_j = Σ_k mult[k,i,j] * e_k
        # This means L_g[i][k, j] = mult[k, i, j]
    return L

def compute_idempotents():
    """Compute primitive idempotents e_j = (1/ℓ) Σ_{a=0}^{ℓ-1} q^{-ja} K^a.
    Returns e_j as vectors in C^DIM."""
    e = []
    for j in range(ELL):
        v = np.zeros(DIM, dtype=complex)
        for a in range(ELL):
            # K^a is basis[idx(a, 0, 0)]
            coeff = Q ** (-j * a) / ELL
            v[idx(a, 0, 0)] += coeff
        e.append(v)
    return e

def compute_projective_indecomposable(L, e_j):
    """P(j) = A · e_j (left ideal). Compute as the column space of Σ_i L_g[i] · e_j[i].
    Actually, P(j) = A · e_j = {a · e_j : a ∈ A} = span of all (basis[i] · e_j).
    As a matrix: P(j) = Σ_i L_g[i] · e_j[i] ... no.
    
    P(j) = A · e_j is the image of right-multiplication by e_j.
    Right-multiplication by e_j: R_{e_j}(a) = a · e_j.
    R_{e_j} = Σ_i e_j[i] · R_g[i] where R_g[i] is right-multiplication by basis[i].
    
    R_g[i][k, j] = mult[k, j, i]  (since basis[j] * basis[i] = Σ_k mult[k,j,i] basis[k])
    
    So P(j) = column space of R_{e_j} = column space of Σ_i e_j[i] * R_g[i].
    """
    # Build right-multiplication by e_j
    R_ej = np.zeros((DIM, DIM), dtype=complex)
    for i in range(DIM):
        if abs(e_j[i]) > 1e-14:
            # R_g[i] has entries R_g[i][k, j] = mult[k, j, i]
            R_ej += e_j[i] * mult[:, :, i]  # Wait, this is wrong shape.
    # Actually: R_{e_j} = Σ_i e_j[i] * (matrix with [k,j] = mult[k,j,i])
    # mult[k, j, i] = coefficient of basis[k] in (basis[j] * basis[i])
    # So (R_{e_j})[k, j] = Σ_i e_j[i] * mult[k, j, i] = (basis[j] * e_j)[k]
    # This is just: for each j, compute basis[j] * e_j as a vector, and put it as column j.
    R_ej = np.zeros((DIM, DIM), dtype=complex)
    for j in range(DIM):
        # basis[j] * e_j = Σ_i e_j[i] * (basis[j] * basis[i]) = Σ_i e_j[i] * Σ_k mult[k,j,i] basis[k]
        col = np.zeros(DIM, dtype=complex)
        for i in range(DIM):
            if abs(e_j[i]) > 1e-14:
                col += e_j[i] * mult[:, j, i]
        R_ej[:, j] = col
    
    # P(j) = column space of R_ej
    # Compute via SVD
    U, s, Vh = np.linalg.svd(R_ej, full_matrices=False)
    rank = np.sum(s > 1e-10 * (s[0] if len(s) > 0 else 1))
    return U[:, :rank], rank

def compute_jacobom_radical(L, mult):
    """Compute the Jacobson radical J = ker(ε) ∩ nilpotent ideal.
    For u_q(sl_2), J = ker(ε) = augmentation ideal.
    J = span{basis[i] : ε(basis[i]) = 0} = all basis elements except 1 = K^0 E^0 F^0.
    But more precisely, J is the ideal generated by E, F, K-1.
    
    Actually, for a finite-dimensional Hopf algebra over C, the Jacobson radical
    equals the augmentation ideal's nilpotent part. For u_q(sl_2) at ℓ=3:
    J = span{E^b F^c K^a : (b,c) ≠ (0,0)} ∪ {K^a - 1 : a > 0}
    
    More precisely: J is generated (as a two-sided ideal) by E, F, and K-1.
    Since K is invertible (K^3=1), K-1 generates the same ideal as {K-1, K^2-1}.
    
    For the computation: J = ker(ε) where ε(K^a E^b F^c) = 1 if b=c=0 else 0.
    This is a vector subspace of A, but NOT an ideal by itself. The Jacobson
    radical is the LARGEST nilpotent ideal contained in ker(ε).
    
    For u_q(sl_2), J = ker(ε) IS nilpotent (since E, F are nilpotent and K-1
    is nilpotent in the quotient). So J = ker(ε).
    """
    eps = np.zeros(DIM, dtype=complex)
    for a in range(ELL):
        eps[idx(a, 0, 0)] = 1.0
    
    # J = ker(ε) as a vector space
    # But J as an IDEAL is the ideal generated by E, F, K-1.
    # For the projective resolution, we need J as a left module acting on P(j).
    # J * P(j) = span of all (j_elem * p) where j_elem ∈ J, p ∈ P(j).
    
    # Actually, the radical of P(j) is J * P(j) (the left action of J on P(j)).
    # J is the ideal generated by E, F, K-1. As a vector space, J = ker(ε).
    # But the IDEAL J is not the same as the vector space ker(ε) — it's the
    # ideal GENERATED by ker(ε).
    
    # For u_q(sl_2) at ℓ=3: the ideal generated by E is the span of all
    # products containing E. Since E^3 = 0, this is finite.
    # Similarly for F. And K-1 = K - 1.
    
    # The simplest approach: J = ker(ε) as a set of vectors. Check if J is nilpotent.
    # J * J = span of all products j1 * j2 where j1, j2 ∈ J.
    # If J * J ⊊ J (strict), then J is nilpotent.
    
    # For u_q(sl_2), J = span of all basis elements except K^0 E^0 F^0 = 1.
    # dim J = 26.
    
    # Let's just use J = ker(ε) = span{basis[i] : i ≠ idx(0,0,0)}.
    J_basis = [i for i in range(DIM) if abs(eps[i]) < 1e-12]
    return J_basis, eps

def radical_of_module(L, P_basis, J_basis):
    """Compute rad(P) = J · P where J is the Jacobson radical and P is a left module.
    
    P is given as a set of basis vectors (indices into A).
    J · P = span of all (j * p) where j ∈ J, p ∈ P.
    
    Returns the basis of rad(P) as a matrix (columns are basis vectors in C^DIM).
    """
    # Build the matrix whose columns are all products j * p for j in J, p in P
    products = []
    for j_idx in J_basis:
        for p_idx in P_basis:
            # j * p = Σ_k mult[k, j_idx, p_idx] * basis[k]
            col = mult[:, j_idx, p_idx]
            if np.linalg.norm(col) > 1e-14:
                products.append(col)
    
    if not products:
        return np.zeros((DIM, 0), dtype=complex)
    
    M = np.array(products).T  # shape (DIM, n_products)
    # Column space = rad(P)
    U, s, Vh = np.linalg.svd(M, full_matrices=False)
    rank = np.sum(s > 1e-10 * (s[0] if len(s) > 0 else 1))
    return U[:, :rank]

def decompose_into_simples(module_basis, idempotents, L):
    """Decompose a module into simple modules using the idempotents.
    
    For each simple S(j), the multiplicity of S(j) in the module M is:
    m_j = dim(e_j * M) / dim(S(j))
    
    where e_j * M = {e_j * m : m ∈ M} is the e_j-isotypic component.
    """
    mults = []
    for j, e_j in enumerate(idempotents):
        # e_j * M: for each column m in module_basis, compute e_j * m
        # e_j * m = Σ_i e_j[i] * (basis[i] * m) = Σ_i e_j[i] * L_g[i] @ m
        # But L_g[i] @ m gives the vector basis[i] * m.
        # Actually: (e_j * m)[k] = Σ_i e_j[i] * mult[k, i, m_idx] for each m_idx in the basis of M.
        # This is: for each basis vector m of M, compute e_j * m as a vector.
        
        ej_M = []
        for col in range(module_basis.shape[1]):
            m = module_basis[:, col]
            # e_j * m = Σ_i e_j[i] * (basis[i] * m)
            result = np.zeros(DIM, dtype=complex)
            for i in range(DIM):
                if abs(e_j[i]) > 1e-14:
                    # basis[i] * m = L_g[i] @ m... but L_g[i] is left-mult by basis[i]
                    # L_g[i][k, j] = mult[k, i, j], so (L_g[i] @ m)[k] = Σ_j mult[k, i, j] * m[j]
                    result += e_j[i] * (mult[:, i, :] @ m)
            ej_M.append(result)
        
        if not ej_M:
            mults.append(0)
            continue
        
        M_ej = np.array(ej_M).T  # shape (DIM, n_cols)
        U, s, Vh = np.linalg.svd(M_ej, full_matrices=False)
        rank = np.sum(s > 1e-10 * (s[0] if len(s) > 0 else 1))
        # dim S(j) = j + 1 for u_q(sl_2)
        dim_S_j = j + 1
        multiplicity = rank // dim_S_j
        mults.append(multiplicity)
    
    return mults

